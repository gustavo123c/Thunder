#!/usr/bin/env node
/**
 * Generates src/features/health/anatomy-data.ts from the MIT-licensed anatomical
 * SVG paths of `react-native-body-highlighter` (devDependency).
 *
 * Each path is classified as left / right / center of the drawing by measuring
 * its real bounding box in Chromium (Playwright), so the app knows which side of
 * the body every muscle shape belongs to — the source data leaves many shapes
 * unlabeled (e.g. female knees).
 *
 * Usage: node scripts/generate-anatomy.cjs   (needs Playwright + Chromium)
 */
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');

const ASSETS = path.join(__dirname, '..', 'node_modules', 'react-native-body-highlighter', 'dist', 'assets');
const OUT = path.join(__dirname, '..', 'src', 'features', 'health', 'anatomy-data.ts');

// View boxes used by the library's wrappers.
const SOURCES = [
  { sex: 'male', view: 'front', file: 'bodyFront', key: 'bodyFront', viewBox: '0 0 724 1448' },
  { sex: 'male', view: 'back', file: 'bodyBack', key: 'bodyBack', viewBox: '724 0 724 1448' },
  { sex: 'female', view: 'front', file: 'bodyFemaleFront', key: 'bodyFemaleFront', viewBox: '-50 -40 734 1538' },
  { sex: 'female', view: 'back', file: 'bodyFemaleBack', key: 'bodyFemaleBack', viewBox: '756 0 774 1448' },
];

const CENTER_TOLERANCE = 14; // svg units

async function main() {
  const browser = await chromium.launch();
  const page = await browser.newPage();
  const result = {};

  for (const source of SOURCES) {
    const parts = require(path.join(ASSETS, source.file))[source.key];
    const flat = [];
    for (const part of parts) {
      for (const group of ['common', 'left', 'right']) {
        for (const d of part.path?.[group] ?? []) flat.push({ slug: part.slug, group, d });
      }
    }

    const boxes = await page.evaluate(
      ({ flat, viewBox }) => {
        const ns = 'http://www.w3.org/2000/svg';
        const svg = document.createElementNS(ns, 'svg');
        svg.setAttribute('viewBox', viewBox);
        document.body.appendChild(svg);
        const out = flat.map(({ d }) => {
          const el = document.createElementNS(ns, 'path');
          el.setAttribute('d', d);
          svg.appendChild(el);
          const b = el.getBBox();
          return { cx: b.x + b.width / 2, minX: b.x, maxX: b.x + b.width };
        });
        svg.remove();
        return out;
      },
      { flat, viewBox: source.viewBox },
    );

    // Body midline = center of the whole drawing (hands make it symmetric).
    const minX = Math.min(...boxes.map((b) => b.minX));
    const maxX = Math.max(...boxes.map((b) => b.maxX));
    const midline = (minX + maxX) / 2;

    result[`${source.sex}_${source.view}`] = {
      viewBox: source.viewBox,
      paths: flat.map((p, i) => {
        const { cx } = boxes[i];
        const screenSide =
          Math.abs(cx - midline) <= CENTER_TOLERANCE ? 'center' : cx < midline ? 'left' : 'right';
        return { slug: p.slug, screenSide, d: p.d };
      }),
    };
  }
  await browser.close();

  const pkg = require(path.join(ASSETS, '..', '..', 'package.json'));
  const header = `// AUTO-GENERATED by scripts/generate-anatomy.cjs — do not edit by hand.
//
// Anatomical body paths from react-native-body-highlighter@${pkg.version}
// (https://github.com/HichamELBSI/react-native-body-highlighter), MIT License,
// Copyright (c) HichamELBSI. Paths are reproduced unchanged; \`screenSide\` was
// added by measuring each path's bounding box (left/right of the drawing).

export type AnatomySlug =
  | 'abs' | 'adductors' | 'ankles' | 'biceps' | 'calves' | 'chest' | 'deltoids'
  | 'feet' | 'forearm' | 'gluteal' | 'hamstring' | 'hands' | 'hair' | 'head'
  | 'knees' | 'lower-back' | 'neck' | 'obliques' | 'quadriceps' | 'tibialis'
  | 'trapezius' | 'triceps' | 'upper-back';

export type AnatomyPath = { slug: AnatomySlug; screenSide: 'left' | 'right' | 'center'; d: string };
export type AnatomyDrawing = { viewBox: string; paths: AnatomyPath[] };
`;
  const body = Object.entries(result)
    .map(([name, drawing]) => `export const ${name}: AnatomyDrawing = ${JSON.stringify(drawing)};`)
    .join('\n\n');
  fs.writeFileSync(OUT, `${header}\n${body}\n`);
  console.log(`wrote ${OUT}`);
  for (const [name, drawing] of Object.entries(result)) {
    const counts = drawing.paths.reduce((acc, p) => ((acc[p.screenSide] = (acc[p.screenSide] ?? 0) + 1), acc), {});
    console.log(name, counts);
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
